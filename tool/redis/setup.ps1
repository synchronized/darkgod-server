param(
    [int]$InstanceCount = 2,
    [int]$BasePort = 6379
)

$ErrorActionPreference = "Stop"

$projectDir = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$templatePath = Join-Path $PSScriptRoot "redis.conf"
$dataRoot = Join-Path $projectDir "var\redis"
$template = Get-Content -LiteralPath $templatePath -Raw

for ($index = 0; $index -lt $InstanceCount; $index++) {
    $directory = Join-Path $dataRoot ("redis{0}" -f $index)
    New-Item -ItemType Directory -Force -Path $directory | Out-Null

    $port = $BasePort + $index
    $pidFileName = "redis{0}.pid" -f $index
    $logFileName = "redis{0}.log" -f $index
    $dbName = "redis{0}.rdb" -f $index
    $configPath = Join-Path $directory ("redis{0}.conf" -f $index)
    $overrides = @"

# Windows development overrides generated by tool/redis/setup.ps1
daemonize no
bind 127.0.0.1
port $port
pidfile "$pidFileName"
logfile "$logFileName"
dir "."
dbfilename $dbName
"@
    Set-Content -LiteralPath $configPath -Value ($template + $overrides) -Encoding utf8
    Write-Host "Generated $configPath"
}
